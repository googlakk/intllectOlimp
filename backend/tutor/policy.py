@dataclass(frozen=True)
class GradeProfile:
    band: str
    sentences: str
    language: str
    offer_after_errors: int
    hint_size: str


def grade_profile(grade: int | None) -> GradeProfile:
    """Подстройка под возраст: длина, слова, когда предлагать помощь, размер подсказки."""
    if grade is not None and grade <= 6:
        return GradeProfile("5–6 класс", "1–2 коротких предложения", "бытовые слова и примеры из жизни", 1, "очень мелкий шаг")
    if grade is not None and grade >= 10:
        return GradeProfile("10–11 класс", "до 3–4 предложений", "точные термины предмета", 2, "крупный шаг, спрашивай «почему»")
    return GradeProfile("7–9 класс", "2–3 предложения", "термины с коротким пояснением", 2, "средний шаг")


def lesson_character(grade: int | None, subject_label: str, show_path: str, language: str) -> str:
    """Подстройка характера под класс и предмет — часть кэшируемого контекста урока."""
    profile = grade_profile(grade)
    language_name = "кыргызском" if language == "ky" else "русском"
    return (
        f"Ученик: {profile.band}. Длина реплики: {profile.sentences}. Язык: {profile.language}. "
        f"Размер подсказки: {profile.hint_size}.\n"
        f"Предмет: {subject_label}. Как вести к ответу в этом предмете: {show_path}.\n"
        f"Отвечай на {language_name} языке."
    )


