revoke all on public.organizations, public.profiles, public.classrooms,
  public.classroom_teachers, public.classroom_students, public.account_events
  from anon, authenticated;
grant select on public.organizations, public.profiles, public.classrooms,
  public.classroom_teachers, public.classroom_students to authenticated;

create policy "organization members can read organization"
on public.organizations for select to authenticated
using (id = (select organization_id from public.profiles where id = public.current_profile_id()));

create policy "profiles are scoped to self admin or assigned teacher"
on public.profiles for select to authenticated
using (
  id = public.current_profile_id()
  or public.current_profile_role() = 'admin'
  or (
    public.current_profile_role() = 'teacher' and role = 'student' and exists (
      select 1 from public.classroom_students cs
      join public.classroom_teachers ct on ct.classroom_id = cs.classroom_id
      join public.profiles viewer on viewer.teacher_id = ct.teacher_id
      where cs.student_id = profiles.student_id and cs.left_at is null
        and viewer.id = public.current_profile_id()
    )
  )
);

create policy "classrooms are visible to assigned members"
on public.classrooms for select to authenticated
using (public.can_access_classroom(id));

create policy "classroom teachers are visible to classroom members"
on public.classroom_teachers for select to authenticated
using (public.can_access_classroom(classroom_id));

create policy "classroom students are visible to classroom members"
on public.classroom_students for select to authenticated
using (public.can_access_classroom(classroom_id));

