export function calculateDensity(massGrams: number, volumeCm3: number): number {
  if (!Number.isFinite(massGrams) || massGrams < 0 || !Number.isFinite(volumeCm3) || volumeCm3 <= 0) {
    throw new RangeError('Масса должна быть неотрицательной, объём — положительным.');
  }
  return massGrams / volumeCm3;
}

export function densityToSI(gramsPerCm3: number): number {
  return gramsPerCm3 * 1000;
}
